export const KORAT_DISTRICTS = koratGeojson.features.map(f => f.properties.amp_th).sort();

export const isPointInPolygon = (lat: number, lng: number, coordinates: any) => {
  let x = lng, y = lat;
  let inside = false;
  const polys = Array.isArray(coordinates[0][0][0]) ? coordinates : [coordinates];
  for (const poly of polys) {
    const vs = poly[0];
    for (let i = 0, j = vs.length - 1; i < vs.length; j = i++) {
      let xi = vs[i][0], yi = vs[i][1];
      let xj = vs[j][0], yj = vs[j][1];
      let intersect = ((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi);
      if (intersect) inside = !inside;
    }
    if (inside) return true;
  }
  return inside;
};

export const findDistrictByCoords = (lat: number, lng: number) => {
  for (const feature of koratGeojson.features) {
    if (isPointInPolygon(lat, lng, feature.geometry.coordinates)) {
      return feature.properties.amp_th;
    }
  }
  return "";
};
